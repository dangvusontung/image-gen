import { expect, test } from '@playwright/test'

test('separate sticker app creates, edits, generates, reloads and exports a pack', async ({ page }, testInfo) => {
  await page.goto('/stickers.html')
  await expect(page.getByRole('heading', { name: /Every mood/ })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('sticker-welcome.png'), fullPage: true })
  await page.getByRole('button', { name: 'Make your first pack' }).click()
  const create = page.getByRole('dialog')
  await create.getByLabel('Pack name').fill('Little daily moods')
  await create.getByRole('checkbox').check()
  await create.getByRole('button', { name: 'Create pack' }).click()
  await expect(page.getByRole('heading', { name: /Little daily moods/ })).toBeVisible()
  await page.getByLabel('Generation model', { exact: true }).selectOption(JSON.stringify(['mock', 'mock-small-refs']))
  await expect(page.locator('.ss-model-note')).toContainText('mock-small-refs')
  await page.reload()
  await expect(page.getByLabel('Generation model', { exact: true })).toHaveValue(JSON.stringify(['mock', 'mock-small-refs']))
  await page.getByLabel('Generation model', { exact: true }).selectOption(JSON.stringify(['mock', 'mock-v1']))
  await expect(page.locator('.ss-model-note')).toContainText('mock-v1')
  const photo = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 128; canvas.height = 128
    const context = canvas.getContext('2d')!; context.fillStyle = '#ffc85c'; context.fillRect(0, 0, 128, 128)
    return canvas.toDataURL('image/png').split(',')[1]
  })
  await page.evaluate(async encoded => {
    const blob = await (await fetch(`data:image/png;base64,${encoded}`)).blob()
    const clipboard = new DataTransfer()
    clipboard.items.add(new File([blob], 'reference.png', { type: 'image/png' }))
    document.dispatchEvent(new ClipboardEvent('paste', { clipboardData: clipboard, bubbles: true, cancelable: true }))
  }, photo)
  await expect(page.getByRole('img', { name: 'reference.png' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Generate 12 stickers', exact: true })).toBeDisabled()
  await page.getByLabel('Character concept brief', { exact: true }).fill('A friendly character in a cozy purple hoodie, keep the hairstyle and glasses.')
  await page.getByRole('button', { name: 'Save concept brief', exact: true }).click()
  await page.getByRole('button', { name: 'Generate character concepts', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm concept generation', exact: true }).click()
  await expect(page.getByLabel('Generation model', { exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Approve this look', exact: true }).first()).toBeEnabled({ timeout: 30_000 })
  await page.screenshot({ path: testInfo.outputPath('character-concept-review.png'), fullPage: true })
  await page.getByRole('button', { name: 'Approve this look', exact: true }).first().click()
  await expect(page.getByText('Look approved', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit sticker 1', exact: true }).click()
  const editor = page.getByRole('dialog')
  await editor.getByLabel('What they say', { exact: true }).fill('Hey there!')
  await editor.getByRole('button', { name: 'Save expression' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Select all stickers' }).uncheck()
  for (const i of [1, 2, 3]) await page.getByRole('checkbox', { name: `Select sticker ${i}`, exact: true }).check()
  await page.getByRole('button', { name: 'Generate 3 stickers', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Free', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Confirm & generate' }).click()
  await expect(page.locator('.ss-ready-count')).toHaveText('3 / 12 ready', { timeout: 30_000 })
  await expect(page.locator('.ss-art img')).toHaveCount(3)
  await expect.poll(() => page.locator('.ss-art img').evaluateAll(images => images.every(img => (img as HTMLImageElement).naturalWidth === 512))).toBe(true)
  await expect(page.locator('.ss-card-error')).toHaveCount(0)
  const artworkJob = await page.locator('.ss-art img').first().getAttribute('src')
  await page.getByRole('button', { name: 'Edit sticker 1', exact: true }).click()
  await page.getByLabel('What they say', { exact: true }).fill('Ủa, thiệt luôn?')
  await page.getByRole('button', { name: 'Speech bubble', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Sticker with your dialogue' })).toBeVisible()
  await page.getByLabel('Drag text position').focus()
  await page.keyboard.press('ArrowRight')
  await page.screenshot({ path: testInfo.outputPath('sticker-dialogue-editor.png'), fullPage: true })
  await page.getByRole('button', { name: 'Save expression' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.ss-ready-count')).toHaveText('3 / 12 ready')
  const updatedArtwork = await page.locator('.ss-art img').first().getAttribute('src')
  expect(new URL(updatedArtwork!, 'http://localhost').searchParams.get('job_id')).toBe(new URL(artworkJob!, 'http://localhost').searchParams.get('job_id'))
  await page.screenshot({ path: testInfo.outputPath('sticker-editor-desktop.png'), fullPage: true })
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: /WhatsApp WebP pack/ }).click()
  expect((await download).suggestedFilename()).toBe('whatsapp-stickers.zip')
  await page.reload()
  await expect(page.locator('.ss-ready-count')).toHaveText('3 / 12 ready')
  await expect(page.getByRole('heading', { name: /Little daily moods/ })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(async () => { window.scrollTo(0, 0); await document.fonts.ready; await new Promise(requestAnimationFrame); await new Promise(requestAnimationFrame) })
  await expect.poll(() => page.locator('.ss-art img').evaluateAll(images => images.every(img => (img as HTMLImageElement).naturalWidth === 512))).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('sticker-editor-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const telegram = page.waitForEvent('download')
  await page.getByRole('button', { name: /Telegram WebP pack/ }).click()
  expect((await telegram).suggestedFilename()).toBe('telegram-stickers.zip')
})
