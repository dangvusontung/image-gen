import { expect, test } from '@playwright/test'

test('hybrid workflow selection persists and shows Gemini draft defaults', async ({ page, request }) => {
  const response = await request.post('http://127.0.0.1:8100/api/projects', { data: { name: 'Hybrid settings E2E' } })
  const project = await response.json()
  await page.goto('/')
  await page.getByText('Hybrid settings E2E', { exact: true }).click()
  await page.getByLabel('Quy trình tạo ảnh').selectOption('hybrid')
  await expect(page.getByText(/Nâng cấp: FLUX.2 Pro ở 1MP/)).toBeVisible()
  await expect.poll(async () => (await (await request.get(`http://127.0.0.1:8100/api/projects/${project.id}`)).json()).workflow_mode).toBe('hybrid')
  await page.reload()
  await expect(page.getByLabel('Quy trình tạo ảnh')).toHaveValue('hybrid')
  await page.getByRole('tab', { name: '4. Concept' }).click()
  // Size lives in the pinned switcher now, and hybrid mode picks it per step.
  await expect(page.getByText('Quy trình tiết kiệm · model theo từng bước')).toBeVisible()
  await page.getByLabel('Quy trình tạo ảnh').selectOption('hybrid_gemini')
  await expect(page.getByText(/Nâng cấp: Gemini Nano Banana 2.1 ở 1K/)).toBeVisible()
  await page.getByLabel('Quy trình tạo ảnh').selectOption('manual')
  await expect(page.getByLabel('Model', { exact: true })).toBeVisible()
})

