import { expect, test } from '@playwright/test'

test('emoji marks filter concepts, persist after reload, and share defaults across projects', async ({ page, request }) => {
  for (const name of ['Emoji first', 'Emoji second']) {
    await request.post('http://127.0.0.1:8100/api/projects', { data: { name } })
  }
  await page.goto('/')
  await page.getByText('Emoji first', { exact: true }).click()
  await page.getByRole('tab', { name: '4. Concept' }).click()
  await page.getByText('129 concept · Mở/đóng danh sách', { exact: true }).click()
  await page.getByLabel('Emoji concept 131', { exact: true }).selectOption('⭐')
  await page.getByLabel('Emoji concept 135', { exact: true }).selectOption('⭐')
  await page.getByLabel('Lọc concept theo emoji').selectOption('⭐')
  await expect(page.getByRole('button', { name: 'Xem chi tiết concept 131', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Xem chi tiết concept 135', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Xem chi tiết concept 132', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Chỉ chọn các concept đang hiện' }).click()
  await expect(page.getByRole('button', { name: 'Tạo ảnh cho 2 concept', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('tab', { name: '4. Concept' }).click()
  await page.getByText('129 concept · Mở/đóng danh sách', { exact: true }).click()
  await expect(page.getByLabel('Emoji concept 131', { exact: true })).toHaveValue('⭐')
  await page.goto('/')
  await page.getByText('Emoji second', { exact: true }).click()
  await page.getByRole('tab', { name: '4. Concept' }).click()
  await page.getByText('129 concept · Mở/đóng danh sách', { exact: true }).click()
  await expect(page.getByLabel('Emoji concept 131', { exact: true })).toHaveValue('⭐')
  await page.getByLabel('Emoji concept 131', { exact: true }).selectOption('')
  await page.getByLabel('Lọc concept theo emoji').selectOption('⭐')
  await expect(page.getByRole('button', { name: 'Xem chi tiết concept 131', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Xem chi tiết concept 135', exact: true })).toBeVisible()
})

test('bookmarks are independent of emoji and footwear is independent of clothing', async ({ page, request }) => {
  await request.post('http://127.0.0.1:8100/api/projects', { data: { name: 'Bookmark heels E2E' } })
  await page.goto('/')
  await page.getByText('Bookmark heels E2E', { exact: true }).click()
  await page.getByRole('tab', { name: '4. Concept' }).click()
  await expect(page.getByLabel('Đổi giày concept')).toHaveValue('auto')
  await page.getByLabel('Đổi giày concept').selectOption('white_slingback')
  await expect(page.getByLabel('Đổi trang phục concept')).toHaveValue('auto')
  await page.getByLabel('Đổi trang phục concept').selectOption('black_strapless_mini')
  await expect(page.getByLabel('Đổi giày concept')).toHaveValue('white_slingback')
  await page.getByText('129 concept · Mở/đóng danh sách', { exact: true }).click()
  await page.getByRole('button', { name: 'Bookmark concept 136', exact: true }).click()
  await page.getByLabel('Lọc concept theo emoji').selectOption('bookmarked')
  await expect(page.getByRole('button', { name: 'Xem chi tiết concept 136', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Xem chi tiết concept 137', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Emoji concept 136', { exact: true })).toHaveValue('')
  await page.reload()
  await page.getByRole('tab', { name: '4. Concept' }).click()
  await page.getByText('129 concept · Mở/đóng danh sách', { exact: true }).click()
  await expect(page.getByRole('button', { name: 'Bookmark concept 136', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('Đổi giày concept')).toHaveValue('white_slingback')
})
